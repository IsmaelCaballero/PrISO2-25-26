-- El esquema es autoritativo desde CFG-01 (spring.jpa.hibernate.ddl-auto = none).

CREATE TABLE catalogo_prueba (
    id                                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                              VARCHAR(40)   NOT NULL,
    nombre                              VARCHAR(120)  NOT NULL,
    categoria                           VARCHAR(20)   NOT NULL,
    requiere_cita                       BOOLEAN       NOT NULL,
    duracion_minutos                    INTEGER       NOT NULL,
    activa                              BOOLEAN       NOT NULL,
    protocolo_preparacion               VARCHAR(1000) NOT NULL,
    protocolo_ayuno_horas               INTEGER       NOT NULL,
    protocolo_contraindicaciones        VARCHAR(1000) NOT NULL,
    politica_plazo_cancelacion_horas   INTEGER       NOT NULL,
    politica_max_cancelaciones         INTEGER       NOT NULL,
    CONSTRAINT uk_catalogo_prueba_codigo UNIQUE (codigo)
);

CREATE TABLE catalogo_auditoria (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accion         VARCHAR(20)  NOT NULL,
    codigo_prueba  VARCHAR(40)  NOT NULL,
    usuario        VARCHAR(100) NOT NULL,
    instante       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    hash           VARCHAR(64)  NOT NULL,
    hash_anterior  VARCHAR(64)
);

CREATE INDEX idx_catalogo_auditoria_codigo ON catalogo_auditoria (codigo_prueba);
